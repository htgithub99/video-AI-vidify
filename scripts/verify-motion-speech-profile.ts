import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { VP as T } from "./motionVoicePacingVerificationTexts.js";
import { MOTION_VOICE_LIBRARY as L, MOTION_VOICE_SPEED as V } from "../src/constants/motionVoice.js";
import { MOTION_STORY_CONFIG as C } from "../src/constants/motionVideo.js";
delete process.env.APP_DATA_DIR;
const root = path.resolve(T.ROOT + randomUUID());
process.env.VIDIFY_STORAGE_DIR = root;
const { motionVoiceLibraryFile } = await import("../src/server/services/motionVoiceLibraryService.js");
const { getMotionRootDirectory } = await import("../src/server/services/motionLibraryService.js");
const { motionSpeechRate, motionSpeechRateProfile, recordSpeechRate } = await import("../src/server/services/motionSpeechRateService.js");
const write = (file: string, value: unknown) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(value));
};
const channels = { channels: [{ id: T.PROFILE_CHANNEL, narratorVoiceId: T.VOICE, roleVoices: {} as Record<string, string>, name: T.NAME, updatedAt: 1 }] };
const reference: any = { target: { rateBasis: V.BASIS.TEXT, rate: 3.6, fingerprint: T.PROFILE_REFERENCE }, correction: 1 };
const script: any = { language: T.LANG, voiceChannel: T.PROFILE_CHANNEL, beats: [{ narration: Array(350).fill(T.PROFILE_WORD).join(" ") }] };
try {
  write(motionVoiceLibraryFile(L.CHANNELS_FILE), channels);
  write(motionVoiceLibraryFile(V.FILE), reference);
  write(path.join(getMotionRootDirectory(), C.SPEECH_RATE_FILE), { channels: { [T.PROFILE_CHANNEL]: { vi: 2.1 } }, global: { vi: 2.2 } });
  assert.equal(motionSpeechRate(T.PROFILE_CHANNEL, T.LANG), 3.6);
  const before = motionSpeechRateProfile(T.PROFILE_CHANNEL);
  assert.equal(recordSpeechRate(script, 100, before), 3.5);
  assert.equal(motionSpeechRate(T.PROFILE_CHANNEL, T.LANG), 3.5);
  reference.target.fingerprint = T.PROFILE_REFERENCE_NEXT;
  reference.target.rate = 3.8;
  write(motionVoiceLibraryFile(V.FILE), reference);
  assert.equal(motionSpeechRate(T.PROFILE_CHANNEL, T.LANG), 3.8);
  assert.equal(recordSpeechRate(script, 100, before), null);
  reference.target.rateBasis = V.BASIS.ACOUSTIC;
  write(motionVoiceLibraryFile(V.FILE), reference);
  assert.equal(motionSpeechRate(T.PROFILE_CHANNEL, T.LANG), C.VI_SYLLABLES_PER_SECOND);
  write(motionVoiceLibraryFile(V.FILE), {});
  assert.equal(motionSpeechRate(T.PROFILE_CHANNEL, T.LANG), C.VI_SYLLABLES_PER_SECOND);
  assert.equal(recordSpeechRate(script, 125), 2.8);
  assert.equal(motionSpeechRate(T.PROFILE_CHANNEL, T.LANG), 2.8);
  assert.equal(motionSpeechRate(T.PROFILE_CHANNEL, "en"), C.EN_WORDS_PER_SECOND);
  channels.channels[0].narratorVoiceId = T.PROFILE_REFERENCE_NEXT;
  write(motionVoiceLibraryFile(L.CHANNELS_FILE), channels);
  assert.equal(motionSpeechRate(T.PROFILE_CHANNEL, T.LANG), C.VI_SYLLABLES_PER_SECOND);
  const fresh = motionSpeechRateProfile(T.PROFILE_CHANNEL);
  write(motionVoiceLibraryFile(L.LIBRARY_FILE), { [T.PROFILE_REFERENCE_NEXT]: { speed: 1.1 } });
  assert.notEqual(motionSpeechRateProfile(T.PROFILE_CHANNEL), fresh);
  assert.equal(recordSpeechRate(script, 100, fresh), null);
  channels.channels[0].roleVoices = { adult_male: T.VOICE, elder_male: T.PROFILE_REFERENCE_NEXT };
  write(motionVoiceLibraryFile(L.CHANNELS_FILE), channels);
  const roleProfile = motionSpeechRateProfile(T.PROFILE_CHANNEL);
  channels.channels[0].roleVoices = { elder_male: T.PROFILE_REFERENCE_NEXT, adult_male: T.VOICE };
  write(motionVoiceLibraryFile(L.CHANNELS_FILE), channels);
  assert.equal(motionSpeechRateProfile(T.PROFILE_CHANNEL), roleProfile);
  channels.channels[0].roleVoices = { adult_male: T.PROFILE_REFERENCE_NEXT, elder_male: T.VOICE };
  write(motionVoiceLibraryFile(L.CHANNELS_FILE), channels);
  assert.notEqual(motionSpeechRateProfile(T.PROFILE_CHANNEL), roleProfile);
  process.stdout.write(T.PROFILE_PASSED);
} finally {
  fs.rmSync(root, { recursive: true, force: true });
}
