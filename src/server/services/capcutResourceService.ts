let cachedCatalog: CapcutCatalog | null = null;
const getRessdkDbPaths = (): string[] => {
  const localAppData = process.env.LOCALAPPDATA || "";
  const baseDir = path.join(localAppData, VIDEO_EXPORT_TEXT_CAPCUT, VIDEO_EXPORT_TEXT_USER_DATA, VIDEO_EXPORT_TEXT_CACHE, VIDEO_EXPORT_TEXT_RESSDK_DB);
  if (!fs.existsSync(baseDir)) return [];
  try {
    const entries = fs.readdirSync(baseDir);
    const dbPaths: string[] = [];
    for (const entry of entries) {
      const dbFile = path.join(baseDir, entry, VIDEO_EXPORT_TEXT_RP_DB);
      if (fs.existsSync(dbFile)) {
        dbPaths.push(dbFile);
      }
    }
    return dbPaths;
  } catch {
    return [];
  }
};
export const getCapcutResourceCatalog = (): CapcutCatalog => {
  if (cachedCatalog) return cachedCatalog;
  const dbPaths = getRessdkDbPaths();
  if (_.isEmpty(dbPaths)) {
    cachedCatalog = FALLBACK_CATALOG;
    return cachedCatalog;
  }
  const effects: CapcutResourceItem[] = [];
  const transitions: CapcutResourceItem[] = [];
  const seenIds = new Set<string>();
  try {
    for (const dbPath of dbPaths) {
      const buffer = fs.readFileSync(dbPath);
      const content = buffer.toString(VIDEO_EXPORT_TEXT_UTF8);
      const regex = /\{"common_attr":\{"id":"(\d+)","effect_id":"(\d+)","effect_type":(\d+),"source":\d+,"title":"([^"]+)"/g;
      let match: RegExpExecArray | null;
      while ((match = regex.exec(content)) !== null) {
        const [, id, effectId, effectTypeStr, rawTitle] = match;
        if (!seenIds.has(effectId)) {
          seenIds.add(effectId);
          const title = _.replace(rawTitle, /\\u([0-9a-fA-F]{4})/g, (_, c) => String.fromCharCode(parseInt(c, 16)));
          const effectType = parseInt(effectTypeStr, 10);
          const item: CapcutResourceItem = { id, effect_id: effectId, effect_type: effectType, title };
          if (effectType === 7) {
            effects.push(item);
          } else if (effectType === 19) {
            transitions.push(item);
          }
        }
      }
    }
    if (!_.isEmpty(effects) || !_.isEmpty(transitions)) {
      cachedCatalog = {
        effects: _.isEmpty(effects) ? FALLBACK_CATALOG.effects : effects,
        transitions: _.isEmpty(transitions) ? FALLBACK_CATALOG.transitions : transitions,
      };
      return cachedCatalog;
    }
  } catch (err: any) {
    logger.warn(VIDEO_EXPORT_TEMPLATE_CAPCUT_RESOURCE_PARSE_RP_DB_ERROR(`${err?.message}`));
  }
  cachedCatalog = FALLBACK_CATALOG;
  return cachedCatalog;
};
