const WEAK = new Set<string>([MOTION_TEXT_ROOM, MOTION_TEXT_STREET, MOTION_TEXT_CITY, MOTION_TEXT_ROAD, MOTION_TEXT_LIGHT, MOTION_TEXT_HOME, MOTION_TEXT_STATION, MOTION_TEXT_FIELD, MOTION_TEXT_OLD]);
const STOP = new Set<string>([MOTION_TEXT_THE, MOTION_TEXT_A, MOTION_TEXT_AN, MOTION_TEXT_OF, MOTION_TEXT_AND, MOTION_TEXT_WITH, MOTION_TEXT_OLD, MOTION_TEXT_NEW, MOTION_TEXT_BIG, MOTION_TEXT_SMALL, MOTION_TEXT_LARGE]);
const tokens = (s: string): string[] =>
  _.filter(
    _.split(
      _.deburr(_.toLower(_.toString(s)))
        .replace(/[^a-z0-9]+/g, MOTION_TEXT_SYMBOL_13)
        .trim(),
      MOTION_TEXT_SYMBOL_13,
    ),
    (w) => !!w && !STOP.has(w),
  );
const singular = (w: string) => (w.length > 3 && w.endsWith(MOTION_TEXT_S) && !w.endsWith(MOTION_TEXT_SS) ? w.slice(0, -1) : w);
export const matchLibraryId = (ids: readonly string[], wanted: unknown): string | null => {
  const raw = _.trim(_.toString(wanted || ""));
  if (!raw || _.isEmpty(ids)) return null;
  if (_.includes(ids, raw)) return raw;
  const idSet = new Set(ids);
  const want = _.map(tokens(raw), singular);
  if (_.isEmpty(want)) return null;
  const joined = want.join(MOTION_TEXT_SYMBOL_30);
  if (idSet.has(joined)) return joined;
  const scores = new Map<string, number>();
  const bump = (id: string, v: number): void => {
    if (idSet.has(id)) scores.set(id, (scores.get(id) || 0) + v);
  };
  _.forEach(want, (w, wi) => {
    const k = WEAK.has(w) ? 0.45 : 1;
    _.forEach(SYNONYMS[w] || [], (id, rank) => bump(id, (2.2 - rank * 0.3 - wi * 0.05) * k));
  });
  _.forEach(ids, (id) => {
    const parts = _.map(_.split(id, MOTION_TEXT_SYMBOL_30), singular);
    let hit = 0;
    _.forEach(want, (w) => {
      if (_.includes(parts, w)) hit += 1;
      else if (w.length >= 4 && _.some(parts, (p) => p.length >= 4 && (p.startsWith(w) || w.startsWith(p)))) hit += 0.6;
    });
    if (hit) bump(id, (hit / Math.max(parts.length, want.length)) * 2);
  });
  if (!scores.size) return null;
  const [best, score] = _.maxBy([...scores.entries()], ([, v]) => v)!;
  return score >= 0.6 ? best : null;
};
