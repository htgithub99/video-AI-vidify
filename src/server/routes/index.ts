import { SOURCE_TEXT_PROXIES } from "../../constants/sourceText.js";
import express from "express";
import { SERVER_ROUTES } from "../../constants/apiRoutes.js";
import { deletePreset, getAllPresets, savePreset } from "../controllers/presetController.js";
import { createProject, deleteProject, getAllProjects, getProjectById, updateProject } from "../controllers/projectController.js";
import { getVoices } from "../controllers/voiceController.js";
import motionVideoRoutes from "../../features/motion/server/routes/motionVideoRoutes.js";
import settingsRoutes from "../../features/settings/server/routes/settingsRoutes.js";
import proxyRoutes from "../../features/proxy/server/routes/proxyRoutes.js";
import shortsRoutes from "../../features/shorts/server/routes/shortsRoutes.js";
import videoExportRoutes from "../../features/video-export/server/routes/videoExportRoutes.js";
const router = express.Router();
router.get(SERVER_ROUTES.PROJECTS, getAllProjects);
router.get(SERVER_ROUTES.PROJECTS_ID, getProjectById);
router.post(SERVER_ROUTES.PROJECTS, createProject);
router.put(SERVER_ROUTES.PROJECTS_ID, updateProject);
router.delete(SERVER_ROUTES.PROJECTS_ID, deleteProject);
router.get(SERVER_ROUTES.PRESETS, getAllPresets);
router.post(SERVER_ROUTES.PRESETS, savePreset);
router.delete(SERVER_ROUTES.PRESETS_ID, deletePreset);
router.get(SERVER_ROUTES.VOICES, getVoices);
router.use(SERVER_ROUTES.SETTINGS, settingsRoutes);
router.use(SOURCE_TEXT_PROXIES, proxyRoutes);
router.use(SERVER_ROUTES.SHORTS, shortsRoutes);
router.use(SERVER_ROUTES.VIDEO_EXPORT, videoExportRoutes);
router.use(SERVER_ROUTES.MOTION_VIDEO, motionVideoRoutes);
export default router;
