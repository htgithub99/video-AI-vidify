import {
  SOURCE_TEMPLATE_AUDIENCE_MARKET_CONTRACT_PRIMARY_MARKET_SELECTED,
  SOURCE_TEXT_EARN_ATTENTION_THROUGH_A_CONCRETE_LOCAL,
  SOURCE_TEXT_EXPLAIN_FOREIGN_INSTITUTIONS_OR_REFERENCES_FROM,
  SOURCE_TEXT_GENERAL,
  SOURCE_TEXT_INTERNATIONAL_ENGLISH,
  SOURCE_TEXT_INTERNATIONAL_ENGLISH_SPEAKING_AUDIENCE,
  SOURCE_TEXT_KEEP_COUNTRY_ETHNICITY_GEOGRAPHY_ARCHITECTURE_CLOTHING,
  SOURCE_TEXT_OPEN_ON_A_CONCRETE_GLOBALLY_UNDERSTANDABLE,
  SOURCE_TEXT_PRESERVE_LOCAL_NAMES_AND_PERSPECTIVES_WHILE,
  SOURCE_TEXT_USE_ACCURATE_VIETNAMESE_GEOGRAPHY_ARCHITECTURE_CLOTHING,
  SOURCE_TEXT_USE_GLOBALLY_INTELLIGIBLE_ENGLISH_SEARCH_INTENT,
  SOURCE_TEXT_USE_NATURAL_VIETNAMESE_SEARCH_INTENT_AND,
  SOURCE_TEXT_VIETNAM,
  SOURCE_TEXT_VIETNAMESE_AUDIENCE_ACROSS_VIETNAM,
  SOURCE_TEXT_WRITE_CLEAR_IDIOMATIC_INTERNATIONAL_ENGLISH_WITH,
  SOURCE_TEXT_WRITE_IDIOMATIC_CONTEMPORARY_VIETNAMESE_WITH_COMPLETE,
} from "../constants/sourceText";
import _ from "lodash";
import { ProjectLanguage } from "../types";
interface AudienceMarketProfile {
  id: "vietnam" | "international_english";
  locale: string;
  narration: string;
  retention: string;
  culturalContext: string;
  visualContext: string;
  seoContext: string;
}
const MARKET_PROFILES: Record<AudienceMarketProfile["id"], AudienceMarketProfile> = {
  vietnam: {
    id: SOURCE_TEXT_VIETNAM,
    locale: SOURCE_TEXT_VIETNAMESE_AUDIENCE_ACROSS_VIETNAM,
    narration: SOURCE_TEXT_WRITE_IDIOMATIC_CONTEMPORARY_VIETNAMESE_WITH_COMPLETE,
    retention: SOURCE_TEXT_EARN_ATTENTION_THROUGH_A_CONCRETE_LOCAL,
    culturalContext: SOURCE_TEXT_EXPLAIN_FOREIGN_INSTITUTIONS_OR_REFERENCES_FROM,
    visualContext: SOURCE_TEXT_USE_ACCURATE_VIETNAMESE_GEOGRAPHY_ARCHITECTURE_CLOTHING,
    seoContext: SOURCE_TEXT_USE_NATURAL_VIETNAMESE_SEARCH_INTENT_AND,
  },
  international_english: {
    id: SOURCE_TEXT_INTERNATIONAL_ENGLISH,
    locale: SOURCE_TEXT_INTERNATIONAL_ENGLISH_SPEAKING_AUDIENCE,
    narration: SOURCE_TEXT_WRITE_CLEAR_IDIOMATIC_INTERNATIONAL_ENGLISH_WITH,
    retention: SOURCE_TEXT_OPEN_ON_A_CONCRETE_GLOBALLY_UNDERSTANDABLE,
    culturalContext: SOURCE_TEXT_PRESERVE_LOCAL_NAMES_AND_PERSPECTIVES_WHILE,
    visualContext: SOURCE_TEXT_KEEP_COUNTRY_ETHNICITY_GEOGRAPHY_ARCHITECTURE_CLOTHING,
    seoContext: SOURCE_TEXT_USE_GLOBALLY_INTELLIGIBLE_ENGLISH_SEARCH_INTENT,
  },
};
const resolveAudienceMarketProfile = (language?: string): AudienceMarketProfile => (_.isEqual(language, ProjectLanguage.VI) ? MARKET_PROFILES.vietnam : MARKET_PROFILES.international_english);
export const createAudienceMarketDirective = (language?: string, audience: string = SOURCE_TEXT_GENERAL): string => {
  const profile = resolveAudienceMarketProfile(language);
  return SOURCE_TEMPLATE_AUDIENCE_MARKET_CONTRACT_PRIMARY_MARKET_SELECTED(`${profile.id}`, `${profile.locale}`, `${_.trim(audience) || SOURCE_TEXT_GENERAL}`, `${profile.narration}`, `${profile.retention}`, `${profile.culturalContext}`, `${profile.visualContext}`, `${profile.seoContext}`);
};
