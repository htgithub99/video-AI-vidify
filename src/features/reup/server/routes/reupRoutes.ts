import express from "express";
import { REUP_API } from "../../constants/reupConfig.js";
import { approveReupScriptController, cancelReupController, deleteReupJobsController, exportReupController, inspectReupSourceController, pickReupFolderController, listReupJobsController, reupFrameController, reupStatusController, rerollReupThumbController, rerunReupController, saveReupStyleController, saveReupVideoController, startReupController } from "../controllers/reupController.js";
const router = express.Router();
router.post(REUP_API.SOURCE, inspectReupSourceController);
router.post(REUP_API.START, startReupController);
router.get(REUP_API.STATUS, reupStatusController);
router.post(REUP_API.APPROVE_SCRIPT, approveReupScriptController);
router.post(REUP_API.SAVE_VIDEO, saveReupVideoController);
router.post(REUP_API.RERUN, rerunReupController);
router.post(REUP_API.EXPORT, exportReupController);
router.post(REUP_API.CANCEL, cancelReupController);
router.get(REUP_API.FRAME, reupFrameController);
router.post(REUP_API.PICK_FOLDER, pickReupFolderController);
router.get(REUP_API.JOBS, listReupJobsController);
router.post(REUP_API.DELETE, deleteReupJobsController);
router.post(REUP_API.THUMB, rerollReupThumbController);
router.post(REUP_API.STYLE, saveReupStyleController);
export default router;
