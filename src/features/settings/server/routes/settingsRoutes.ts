import express from "express";
import { getSettingsFromGAS, saveApiKeys, addGoogleAccount, updateGoogleAccountStatus } from "../controllers/settingsController.js";
import { SETTINGS_API_PATHS } from "../../../../constants/apiRoutes.js";
import { CHROME_BACKUP } from "../../../../constants/chromeBackup.js";
import { getChromeBackup, updateChromeBackup, prepareChromeBackup, addChrome, renameChrome, removeChrome, prepareChrome, checkChrome, clearAvailability } from "../controllers/chromeBackupController.js";
const router = express.Router();
router.get(CHROME_BACKUP.ROUTE, getChromeBackup);
router.put(CHROME_BACKUP.ROUTE, updateChromeBackup);
router.post(CHROME_BACKUP.PREPARE_ROUTE, prepareChromeBackup);
router.post(CHROME_BACKUP.ADD_ROUTE, addChrome);
router.put(CHROME_BACKUP.ITEM_ROUTE, renameChrome);
router.delete(CHROME_BACKUP.ITEM_ROUTE, removeChrome);
router.post(CHROME_BACKUP.ITEM_PREPARE_ROUTE, prepareChrome);
router.post(CHROME_BACKUP.ITEM_CHECK_ROUTE, checkChrome);
router.delete(CHROME_BACKUP.AVAILABILITY_ROUTE, clearAvailability);
router.get(SETTINGS_API_PATHS.GAS_CONFIG, getSettingsFromGAS);
router.post(SETTINGS_API_PATHS.API_KEYS, saveApiKeys);
router.post(SETTINGS_API_PATHS.ACCOUNTS, addGoogleAccount);
router.put(SETTINGS_API_PATHS.ACCOUNTS_STATUS, updateGoogleAccountStatus);
export default router;
